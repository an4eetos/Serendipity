import Link from "next/link";
import { unstable_rethrow } from "next/navigation";
import { Suspense } from "react";
import type { Terms } from "@/lib/types";

const API_URL = process.env.API_URL ?? process.env.NEXT_PUBLIC_API_URL ?? "http://localhost:8787";

// Version shows which terms version the API currently asks readers to accept.
async function Version() {
  let version: string | undefined;
  try {
    const res = await fetch(`${API_URL}/terms`);
    if (res.ok) {
      const data = (await res.json()) as Partial<Terms>;
      if (typeof data.version === "string" && data.version) version = data.version;
    }
  } catch (e) {
    unstable_rethrow(e);
  }
  return version ? <>Version {version}</> : <>version unavailable</>;
}

